def religion_block(group):
    body = "".join(_school_block(r[1]) for r in RITES if r[0] == group)
    return f"{BEGIN}\treligious_schools = {{\n{body}\t}}\n{END}"


def patch_religion_file():
    text = open(REL_FILE, encoding="cp1252").read()
    for group in GROUPS:
        gm = re.search(rf"^{group}\s*=\s*\{{", text, re.M)
        assert gm, f"religion group {group} not found in 00_religion.txt"
        start, end = gm.end(), _match(text, gm.end() - 1)
        body = text[start:end]
        body = re.sub(MARKER_RE, "", body, flags=re.S)
        # the base game's (or an older) religious_schools block at group level
        vm = re.search(r"^\treligious_schools\s*=\s*\{", body, re.M)
        if vm:
            vend = _match(body, vm.end() - 1)
            nl = body.find("\n", vend)
            body = body[: vm.start()] + body[nl + 1:]
        m = re.search(r"^\tflag_emblem_index_range = \{[^\n]*\n", body, re.M)
        assert m, f"{group}: flag_emblem_index_range not found in 00_religion.txt"
        body = body[: m.end()] + "\n" + religion_block(group) + body[m.end():]
        text = text[:start] + body + text[end:]
    open(REL_FILE, "w", encoding="cp1252", newline="").write(text)



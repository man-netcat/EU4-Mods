#!/usr/bin/env python3
"""CK3's rites as EU4 religious schools, for every religion group the mod uses.

Each CK3 rite becomes a school of its religion group, invitable like the
Islamic madhhabs (the Islamic schools of the base game are *replaced* by the
Islamic rites), with one flavour modifier while the cleric is entertained. A
country starts with the school of its CK3 ruler's rite at 867, written as
`religious_school = X` in country history.

Every tag inherits its CK3 title holder's religion and rite, so the two must
agree: verify() fails when a tag's EU4 religion is not one the ruler's rite
belongs to (fix the tag's religion in tags.db), when a ruler has no rite, or
when a religion the mod uses has no rites at all. There are no fallbacks.

`build.py` runs step_rites(), which (re)writes, idempotently:
  - one `religious_schools` block per group in common/religions/00_religion.txt
    (between BEGIN/END RITES markers; the vanilla Islamic block is replaced),
  - common/static_modifiers/karolingian_rites.txt   scholar modifiers,
  - common/scripted_effects/karolingian_rites.txt   clear-other-scholars effect,
  - interface/karolingian_rites.gfx                 one sprite per school,
  - localisation/replace/karolingian_rites_l_english.yml,
  - gfx/interface/icon_rite_<key>.tga   PLACEHOLDER icon, only if missing -
    drop the real CK3 icon in under the same name and it is kept.

The tables below are the source of truth; edit them, not the outputs.
"""

def _vanilla_text(*subdirs):
    from paths import EU4_GAME

    out = []
    for sub in subdirs:
        base = os.path.join(EU4_GAME, sub)
        for root, _d, files in os.walk(base):
            for fn in files:
                if fn.endswith((".txt", ".yml")):
                    out.append(open(os.path.join(root, fn), encoding="utf-8", errors="replace").read())
    return "\n".join(out)


from faiths import ck3_rites  # noqa: E402,F401


def used_religions():
    """Religions the mod actually uses: held by a tag or by a province."""
    import sqlite3

    c = sqlite3.connect(os.path.join(HERE, "tags.db"))
    got = {r[0] for r in c.execute("select religion from tags where religion is not null")}
    got |= {r[0] for r in c.execute("select religion from provinces where religion is not null")}
    c.close()
    return sorted(got)


def verify(check_history=True):
    """The gate: every religion the mod uses must have its rites, every tag must
    follow its ruler's religion and rite, and the schools must match CK3,
    vanilla EU4 and our own outputs. Returns (errors, warnings)."""
    err, warn = [], []

    # 1. the table against CK3
    rites_in_ck3 = ck3_rites()
    for r in RITES:
        if r[2] not in rites_in_ck3:
            err.append(f"{r[1]}: CK3 has no rite '{r[2]}' (renamed in a patch?)")
    if len(set(KEYS)) != len(KEYS) or len(BY_RITE) != len(RITES):
        err.append("duplicate school key or CK3 rite in the table")

    # 2. EVERY religion the mod uses is a lifted CK3 faith with rites, in the group the religion sits in
    rel_text = open(REL_FILE, encoding="cp1252").read()
    groups = religion_groups(rel_text)
    from faiths import FAITH_RELIGION, verify as verify_faiths

    r_of = rite_religions()
    covered = {}
    for key, rel in r_of.items():
        covered.setdefault(rel, []).append(key)
        if groups.get(rel) is None:
            err.append(f"{key}: religion '{rel}' is in no group in 00_religion.txt")
        elif groups[rel] != GROUP_OF_KEY[key]:
            err.append(f"{key} is a {GROUP_OF_KEY[key]} rite but religion '{rel}' sits in group {groups[rel]}")
    for r in RITES:
        if r[1] not in r_of:
            warn.append(f"rite '{r[2]}' (CK3 faith {rites_in_ck3.get(r[2])}) belongs to a faith no EU4 religion lifts yet - no tag or province may use it")
    for rel in used_religions():
        if rel not in covered:
            err.append(f"religion '{rel}' is used by the mod but has no rites - add them to tools/rites.py")
    f_err, f_warn = verify_faiths(used_religions())
    err += f_err
    warn += f_warn

    # 3. everything the generated script leans on exists in vanilla EU4
    defs = _vanilla_text("common/scripted_triggers", "common/event_modifiers", "common/scripted_effects")
    for name in _VANILLA_NEEDS:
        if not re.search(rf"^{re.escape(name)}\s*=", defs, re.M):
            err.append(f"vanilla has no '{name}' ({_VANILLA_NEEDS[name]})")
    used = _vanilla_text("common")
    for mod in sorted({r[5] for r in RITES}):
        mkey = mod.split("=")[0].strip()
        if not re.search(rf"^\s*{re.escape(mkey)}\s*=", used, re.M):
            err.append(f"modifier '{mkey}' is not used anywhere in vanilla common/ (typo?)")
    vloc = _vanilla_text("localisation")
    vrel = _vanilla_text("common/religions")
    for key in KEYS:
        if key in VANILLA_OVERRIDES:
            continue
        for k in (school_name(key), modifier_name(key)):
            if re.search(rf"^\s*{re.escape(k)}:", vloc, re.M):
                err.append(f"{k} is already a vanilla localisation key")
    for key in VANILLA_OVERRIDES:
        if f"\t\t{school_name(key)} = {{" not in vrel:
            err.append(f"override of vanilla school '{school_name(key)}', but vanilla no longer defines it (renamed in a patch?)")
        if GROUP_OF_KEY.get(key) != "muslim":
            err.append(f"vanilla Islamic school '{school_name(key)}' is no longer covered by an Islamic rite")

    # 4. outputs are exactly what the table generates (nobody hand-edited them)
    def same(path, want, label, enc="cp1252"):
        try:
            got = open(path, encoding=enc).read()
        except FileNotFoundError:
            err.append(f"{label} is missing - run tools/build.py")
            return
        if got.replace("\r\n", "\n") != want:
            err.append(f"{label} differs from tools/rites.py output - never hand-edit it; rebuild")

    for g in GROUPS:
        gm = re.search(rf"^{g}\s*=\s*\{{", rel_text, re.M)
        body = rel_text[gm.end(): _match(rel_text, gm.end() - 1)] if gm else ""
        if religion_block(g) not in body:
            err.append(f"00_religion.txt: the {g} rites block is missing or differs from tools/rites.py output; rebuild")
        if len(re.findall(r"^\treligious_schools\s*=", body, re.M)) != 1:
            err.append(f"00_religion.txt: group {g} must have exactly one religious_schools block (the generated one)")
    same(os.path.join(MOD, "common", "static_modifiers", "karolingian_rites.txt"), static_modifiers(), "static_modifiers/karolingian_rites.txt")
    same(os.path.join(MOD, "common", "scripted_effects", "karolingian_rites.txt"), scripted_effects(), "scripted_effects/karolingian_rites.txt")
    same(os.path.join(MOD, "interface", "karolingian_rites.gfx"), gfx(), "interface/karolingian_rites.gfx")
    same(os.path.join(MOD, "localisation", "replace", "karolingian_rites_l_english.yml"),
         "﻿" + localisation(), "karolingian_rites_l_english.yml", enc="utf-8")

    # 5. rite icons: a missing file is an error, a generated placeholder is
    # reported by name (the real CK3 icons go in locally)
    ph = _placeholder_bytes()
    missing, left = [], {}
    for r in RITES:
        key, p = r[1], icon_path(r[1])
        if not os.path.exists(p):
            missing.append(key)
        elif open(p, "rb").read() == ph[key]:
            left.setdefault(r[0], []).append(key)
    if missing:
        err.append("rite icons missing (gfx/interface/icon_rite_<key>.tga): " + ", ".join(missing))
    for g, keys in sorted(left.items()):
        warn.append(f"rite icons still placeholders ({g}): " + ", ".join(keys))

    for r in RITES:
        if not rite_icon_name(r[2]):
            err.append(f"{r[1]}: CK3 names no icon for rite '{r[2]}' (nor for its faith)")
    differ = [r[1] for r in RITES
              if ck3_rite_icon_file(r[2]) and os.path.exists(icon_path(r[1]))
              and open(icon_path(r[1]), "rb").read() != _ck3_icon_tga(ck3_rite_icon_file(r[2]))]
    if differ:
        warn.append("rite icons that differ from CK3's (hand-placed? run tools/faiths.py icons to lift): " + ", ".join(differ))

    # 5b. religion icons: every religion the mod uses has an icon frame in all four strips
    icons = religion_icons(rel_text)
    for rel in used_religions():
        n = icons.get(rel)
        if n is None:
            err.append(f"religion '{rel}' has no icon = N in 00_religion.txt")
            continue
        for strip, px in RELIGION_STRIPS:
            path = os.path.join(MOD, strip)
            if not os.path.exists(path):
                err.append(f"religion icon strip {strip} is missing")
                continue
            frames, visible = strip_frame(path, px, n)
            if n > frames:
                err.append(f"religion '{rel}': icon {n} is outside {os.path.basename(strip)} ({frames} frames)")
            elif not visible:
                err.append(f"religion '{rel}': icon {n} is blank in {os.path.basename(strip)}")

    # 6. every tag follows its ruler: religion and rite agree, and history carries the school
    if check_history:
        import glob

        from tagdb import TAGS

        for t in TAGS:
            rite = holder_rite(t)
            key = BY_RITE.get(rite)
            if rite is None:
                err.append(f"{t.tag}: CK3 gives its 867 ruler no rite")
                continue
            if key is None:
                err.append(f"{t.tag}: ruler's CK3 rite '{rite}' has no school in tools/rites.py")
                continue
            if r_of.get(key) != t.religion:
                err.append(
                    f"{t.tag}: religion '{t.religion}' but its 867 ruler follows the {rite} rite, "
                    f"a CK3 faith lifted as '{r_of.get(key)}' - tags inherit their ruler's religion; fix tags.db"
                )
                continue
            files = glob.glob(os.path.join(MOD, "history", "countries", f"{t.tag} - *.txt"))
            if not files:
                continue  # tag has no history file of its own (vanilla reuse)
            txt = open(files[0], encoding="cp1252").read()
            m = re.search(r"^religious_school = (\w+)", txt, re.M)
            have = m.group(1) if m else None
            if have != school_name(key):
                err.append(f"{t.tag} ({t.religion}): history has {have}, expected {school_name(key)}")
    return err, warn


def step_rites():
    from eu4 import write_out

    patch_religion_file()
    write_out(os.path.join(MOD, "common", "static_modifiers", "karolingian_rites.txt"), static_modifiers())
    write_out(os.path.join(MOD, "common", "scripted_effects", "karolingian_rites.txt"), scripted_effects())
    write_out(os.path.join(MOD, "interface", "karolingian_rites.gfx"), gfx())
    loc = os.path.join(MOD, "localisation", "replace", "karolingian_rites_l_english.yml")
    write_out(loc, "﻿" + localisation(), encoding="utf-8")
    made = placeholder_icons()
    print(f"{len(RITES)} rite schools in {len(GROUPS)} religion groups written; "
          f"{len(made)} placeholder icons created (replace with CK3 icons locally)")
    err, warn = verify(check_history=False)
    for w in warn:
        print("  WARN " + w)
    for e in err:
        print("  FAIL " + e)
    return 1 if err else 0



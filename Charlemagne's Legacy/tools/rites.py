"""CK3's Christian rites as EU4 religious schools (the Islamic-schools mechanism).

Each rite of CK3's christian_faith becomes a school of the `christian`
religion group: invitable like a madhhab, one flavour modifier while the
scholar is entertained, and a country starts with the school of its CK3
ruler's rite at 867 (`religious_school = X` in country history).

`build.py` runs step_rites(), which (re)writes, idempotently:
  - the `religious_schools` block of the christian group in
    common/religions/00_religion.txt (between the BEGIN/END RITES markers),
  - common/static_modifiers/karolingian_rites.txt   scholar modifiers,
  - common/scripted_effects/karolingian_rites.txt   clear-other-scholars effect,
  - interface/karolingian_rites.gfx                 one sprite per school,
  - localisation/replace/karolingian_rites_l_english.yml,
  - gfx/interface/icon_christian_school_<key>.tga   PLACEHOLDER icon, only if
    missing - drop the real CK3 icon in under the same name and it is kept.

The table below is the source of truth; edit it, not the outputs.
"""

def _match(text, open_idx):
    """Index of the brace closing the one at open_idx (comments skipped)."""
    depth, i = 0, open_idx
    while i < len(text):
        c = text[i]
        if c == "#":
            i = text.find("\n", i)
            if i < 0:
                break
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    raise ValueError("unbalanced braces")


def religion_groups(text=None):
    """{religion: group} for every religion in the mod's 00_religion.txt."""
    if text is None:
        text = open(REL_FILE, encoding="cp1252").read()
    out = {}
    for gm in re.finditer(r"^(\w+)\s*=\s*\{", text, re.M):
        grp = gm.group(1)
        end = _match(text, gm.end() - 1)
        body = text[gm.end(): end]
        depth = 0
        for line in body.split("\n"):
            code = line.split("#")[0]
            if depth == 0:
                m = re.match(r"\s*(\w+)\s*=\s*\{", code)
                if m and m.group(1) != "religious_schools":
                    out[m.group(1)] = grp
            depth += code.count("{") - code.count("}")
    return out


# ---- 867 start assignment -------------------------------------------------

def _date_key(s):
    p = [int(x) for x in s.split(".")]
    return tuple(p + [0] * (3 - len(p)))


START = (867, 1, 1)


def rite_at(body):
    """The CK3 rite a character holds at 867.1.1: the latest dated `rite =`
    on or before the start, else the undated one. None if it has none."""
    best, best_key = None, None
    for m in re.finditer(r"^\t(\d+\.\d+\.\d+)\s*=\s*\{(.*?)^\t\}", body, re.M | re.S):
        key = _date_key(m.group(1))
        if key > START:
            continue
        r = re.search(r'^\t\trite\s*=\s*"?(\w+)', m.group(2), re.M)
        if r and (best_key is None or key >= best_key):
            best, best_key = r.group(1), key
    if best:
        return best
    r = re.search(r'^\trite\s*=\s*"?(\w+)', body, re.M)
    return r.group(1) if r else None


def holder_rite(t):
    """The CK3 rite of the tag's 867 title holder, or None if CK3 gives the
    holder none."""
    from ck3 import (TITLES, load_chars, load_dynasties, load_houses,
                     load_titles, resolve)

    if not t.ck3_title or t.tag not in TITLES:
        return None
    chars = load_chars()
    # resolve() directly: ck3_ruler() drops dynasty-less holders (bishops)
    got = resolve(t.tag, load_titles(), chars, load_dynasties(), load_houses())
    body = chars.get(got.get("char", ""))
    return rite_at(body) if body else None


def school_for_tag(t):
    """The school stem of the tag's ruler's rite, or None when the ruler has
    no rite or the table has no school for it (verify() reports both)."""
    return BY_RITE.get(holder_rite(t))


